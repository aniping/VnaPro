inline std::vector<double> GoldenIqForSource(std::uint32_t sourcePort) {
    std::vector<double> expected;
    if (sourcePort >= 4U) {
        return expected;
    }
    expected.reserve(32U);
    for (std::size_t point = 0U; point < 2U; ++point) {
        expected.insert(expected.end(), kGoldenIqBySource[sourcePort][point],
                        kGoldenIqBySource[sourcePort][point] + 16U);
    }
    return expected;
}

