// Returns two independently fixed IQ points; invalid source indices return an empty vector.
inline std::vector<double> GoldenIqForSource(std::uint32_t sourcePort)
{
    std::vector<double> expected;
    if (sourcePort >= 4U) {
        return expected;
    }
    expected.insert(expected.end(), g_goldenIqBySource[sourcePort][0], g_goldenIqBySource[sourcePort][0] + 16U);
    expected.insert(expected.end(), g_goldenIqBySource[sourcePort][1], g_goldenIqBySource[sourcePort][1] + 16U);
    return expected;
}

